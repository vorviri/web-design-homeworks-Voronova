export function createLevel(idx) {
  const raw = getLevelData(idx);
  return {
    platforms: raw.platforms.map(p => new Platform(p.x, p.y, p.w, p.h)),
    crystals: raw.crystals.map((c, i) => new Crystal(c.x, c.y, i)),
    enemies: raw.enemies.map(e => new Enemy(e)),
    tunnel: raw.tunnel,
    story: raw.story
  };
}